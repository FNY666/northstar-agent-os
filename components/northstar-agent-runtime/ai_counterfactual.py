class AICounterfactual:
    """AI-counterfactual decision ledger, Simulated.

    ``counterfactual()`` / ``retire()`` mutate the ledger and consume
    caller seqs; ``verify()`` / ``evaluate()`` and the other views are
    pure reads.
    """

    def __init__(self) -> None:
        self._lock = threading.RLock()
        self._systems: Dict[str, List[str]] = {}
        self._counterfactuals: Dict[str, CounterfactualRecord] = {}
        self._counterfactuals_by_system: Dict[str, List[str]] = {}
        self._retired: Dict[str, RetireRecord] = {}
        self._cfn_counter = 0
        self._seq = 0
        self._audit: List[Dict[str, Any]] = []
        self._rejected = 0

    # -- internal helpers -------------------------------------------------

    def _check_seq(self, seq: Any) -> int:
        if isinstance(seq, bool) or not isinstance(seq, int) or seq < 1:
            raise SeqOrderError("seq must be a positive int, not bool")
        return seq

    def _claim_seq(self, seq: int) -> None:
        """Claim a strictly increasing seq; rewinds raise bare."""
        if seq <= self._seq:
            raise SeqOrderError(
                f"seq must be strictly increasing, got {seq} after {self._seq}"
            )
        self._seq = seq

    def _burn(self, seq: int, method: str, exc: AICounterfactualError) -> None:
        """Book a failed mutation: seq consumed, rejected row appended."""
        self._rejected += 1
        self._audit.append(
            ai_counterfactual_audit_event(
                "rejected",
                seq,
                method=method,
                error=type(exc).__name__,
                error_detail=str(exc),
            )
        )

    def _require_live_system(self, system_id: str) -> None:
        if system_id in self._retired:
            raise RetiredSystemError(f"system already retired: {system_id!r}")

    def _require_known_system(self, system_id: str) -> None:
        if system_id not in self._systems:
            raise UnknownSystemError(f"unknown system: {system_id!r}")

    # -- mutations --------------------------------------------------------

    def counterfactual(
        self,
        system_id: Any,
        seq: Any,
        generation_kind: Any = "input-perturbation",
        verdict: Any = "not-assessed",
        severity: Any = 0,
        counterfactual_digest: Any = "",
    ) -> CounterfactualRecord:
        """Book one declared counterfactual pair (minted ``cfn-N``).

        The first counterfactual registers its system. Severity is a
        host-reported int in [0, 100] booked as data. Raw originals,
        perturbations, feature vectors, and attribution internals
        travel as a digest pin only; they never enter records.
        """
        with self._lock:
            seq_v = self._check_seq(seq)
            self._claim_seq(seq_v)
            try:
                sid = _require_id(system_id, "system_id")
                if sid in self._retired:
                    raise RetiredSystemError(f"system id never recycled: {sid!r}")
                if not isinstance(generation_kind, str) or generation_kind not in GENERATION_KINDS:
                    raise BadGenerationKindError(
                        f"generation_kind must be one of {sorted(GENERATION_KINDS)}"
                    )
                if not isinstance(verdict, str) or verdict not in VERDICTS:
                    raise BadVerdictError(f"verdict must be one of {sorted(VERDICTS)}")
                sev = _require_severity(severity, "severity")
                pin = _require_digest(counterfactual_digest, "counterfactual_digest")
                self._cfn_counter += 1
                cid = f"cfn-{self._cfn_counter}"
                rec = CounterfactualRecord(
                    counterfactual_id=cid,
                    system_id=sid,
                    generation_kind=generation_kind,
                    verdict=verdict,
                    severity=sev,
                    counterfactual_digest=pin,
                    digest=_digest_pin(
                        {
                            "schema": SCHEMA_PIN,
                            "counterfactual_id": cid,
                            "system_id": sid,
                            "generation_kind": generation_kind,
                            "verdict": verdict,
                            "severity": sev,
                            "counterfactual_digest": pin,
                        }
                    ),
                )
                self._counterfactuals[cid] = rec
                self._systems.setdefault(sid, []).append(cid)
                self._counterfactuals_by_system.setdefault(sid, []).append(cid)
                self._audit.append(
                    ai_counterfactual_audit_event(
                        "counterfactualled",
                        seq_v,
                        counterfactual_id=cid,
                        system_id=sid,
                        generation_kind=generation_kind,
                        verdict=verdict,
                        severity=sev,
                    )
                )
                return rec
            except AICounterfactualError as exc:
                self._burn(seq_v, "counterfactual", exc)
                raise

    def retire(
        self,
        system_id: Any,
        seq: Any,
        reason: Any = "manual",
    ) -> RetireRecord:
        """Terminally retire a system id; ids are never recycled."""
        with self._lock:
            seq_v = self._check_seq(seq)
            self._claim_seq(seq_v)
            try:
                sid = _require_id(system_id, "system_id")
                if sid in self._retired:
                    raise RetiredSystemError(f"system already retired: {sid!r}")
                self._require_known_system(sid)
                if not isinstance(reason, str) or reason not in RETIRE_REASONS:
                    raise BadReasonError(
                        f"reason must be one of {sorted(RETIRE_REASONS)}"
                    )
                rec = RetireRecord(
                    system_id=sid,
                    reason=reason,
                    digest=_digest_pin(
                        {
                            "schema": SCHEMA_PIN,
                            "system_id": sid,
                            "reason": reason,
                        }
                    ),
                )
                self._retired[sid] = rec
                self._audit.append(
                    ai_counterfactual_audit_event(
                        "retired",
                        seq_v,
                        system_id=sid,
                        reason=reason,
                    )
                )
                return rec
            except AICounterfactualError as exc:
                self._burn(seq_v, "retire", exc)
                raise

    # -- pure-read views ---------------------------------------------------

    def counterfactual_record(self, counterfactual_id: Any, seq: Any) -> CounterfactualRecord:
        """Return one counterfactual record (pure read)."""
        with self._lock:
            self._check_seq(seq)
            cid = _require_id(counterfactual_id, "counterfactual_id")
            if cid not in self._counterfactuals:
                raise UnknownCounterfactualError(f"unknown counterfactual: {cid!r}")
            return self._counterfactuals[cid]

    def system_ids(self, seq: Any) -> Tuple[str, ...]:
        """All registered system ids in registration order."""
        with self._lock:
            self._check_seq(seq)
            return tuple(self._systems.keys())

    def counterfactual_ids(self, seq: Any) -> Tuple[str, ...]:
        """All counterfactual ids in mint order."""
        with self._lock:
            self._check_seq(seq)
            return tuple(f"cfn-{i}" for i in range(1, self._cfn_counter + 1))

    def counterfactuals_for(self, system_id: Any, seq: Any) -> Tuple[str, ...]:
        """Counterfactual ids booked against one system (mint order)."""
        with self._lock:
            self._check_seq(seq)
            sid = _require_id(system_id, "system_id")
            self._require_known_system(sid)
            return tuple(self._counterfactuals_by_system[sid])

    def retired_ids(self, seq: Any) -> Tuple[str, ...]:
        """All retired system ids."""
        with self._lock:
            self._check_seq(seq)
            return tuple(self._retired.keys())

    def evaluate(self, system_id: Any, seq: Any) -> EvaluationReport:
        """Per-system plausibility tallies and ledger-rule posture (pure read).

        Posture as data: ``unexamined`` (no counterfactuals) ->
        ``implausible`` (any implausible) -> ``contested`` (any
        inconclusive or unverifiable) -> ``unassessed`` (any
        not-assessed) -> ``covered`` (all plausible). ``integrity_ok``
        re-derives every in-scope digest pin as data.
        """
        with self._lock:
            self._check_seq(seq)
            sid = _require_id(system_id, "system_id")
            self._require_known_system(sid)
            cfn_ids = self._counterfactuals_by_system.get(sid, ())
            n_plausible = n_implausible = n_inconclusive = 0
            n_unverifiable = n_not_assessed = 0
            for cid in cfn_ids:
                verdict = self._counterfactuals[cid].verdict
                if verdict == "plausible":
                    n_plausible += 1
                elif verdict == "implausible":
                    n_implausible += 1
                elif verdict == "inconclusive":
                    n_inconclusive += 1
                elif verdict == "unverifiable":
                    n_unverifiable += 1
                else:
                    n_not_assessed += 1
            if not cfn_ids:
                posture = "unexamined"
            elif n_implausible > 0:
                posture = "implausible"
            elif n_inconclusive > 0 or n_unverifiable > 0:
                posture = "contested"
            elif n_not_assessed > 0:
                posture = "unassessed"
            else:
                posture = "covered"
            integrity_ok = all(
                self._counterfactuals[cid].verify() for cid in cfn_ids
            )
            return EvaluationReport(
                system_id=sid,
                n_counterfactuals=len(cfn_ids),
                n_plausible=n_plausible,
                n_implausible=n_implausible,
                n_inconclusive=n_inconclusive,
                n_unverifiable=n_unverifiable,
                n_not_assessed=n_not_assessed,
                posture=posture,
                integrity_ok=integrity_ok,
                digest=_digest_pin(
                    {
                        "schema": SCHEMA_PIN,
                        "system_id": sid,
                        "n_counterfactuals": len(cfn_ids),
                        "n_plausible": n_plausible,
                        "n_implausible": n_implausible,
                        "n_inconclusive": n_inconclusive,
                        "n_unverifiable": n_unverifiable,
                        "n_not_assessed": n_not_assessed,
                        "posture": posture,
                        "integrity_ok": integrity_ok,
                    }
                ),
            )

    def verify(self, record_id: Any, seq: Any) -> VerificationReport:
        """Re-derive one counterfactual record's digest pin (pure read).

        Seq shape validated only, never consumed, no audit row.
        Verdict ``verified`` / ``tampered`` booked as data; tamper is
        reported, never raised.
        """
        with self._lock:
            self._check_seq(seq)
            rid = _require_id(record_id, "record_id")
            if rid in self._counterfactuals:
                rec = self._counterfactuals[rid]
                kind = "counterfactual"
            else:
                raise UnknownCounterfactualError(f"unknown record: {rid!r}")
            verdict = "verified" if rec.verify() else "tampered"
            return VerificationReport(
                record_id=rid,
                record_kind=kind,
                verdict=verdict,
                digest=_digest_pin(
                    {
                        "schema": SCHEMA_PIN,
                        "record_id": rid,
                        "record_kind": kind,
                        "verdict": verdict,
                    }
                ),
            )

    def audit_log(self, seq: Any) -> Tuple[Dict[str, Any], ...]:
        """All audit rows so far (pure read)."""
        with self._lock:
            self._check_seq(seq)
            return tuple(self._audit)

    def stats(self, seq: Any) -> Dict[str, int]:
        """Ledger counters (pure read)."""
        with self._lock:
            self._check_seq(seq)
            return {
                "systems": len(self._systems),
                "counterfactuals": len(self._counterfactuals),
                "retired": len(self._retired),
                "rejected": self._rejected,
            }

