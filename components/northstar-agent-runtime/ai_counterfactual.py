"""AI counterfactual: declared what-if decision ledger, Simulated.

Research note: counterfactual explanations ("what minimal change would
flip this decision?") are a staple of the interpretability literature,
but a *booked* counterfactual never proves the model would have
behaved that way - the perturbation is generated by the host under a
declared method, the originals never enter the ledger, and every
verdict is booked as data. What matters here is the *decision ledger*:
which systems had which declared counterfactual generations, under
which pinned generation-method vocabulary, with what declared
plausibility verdict and evidence digest pin - defensible
bookkeeping, never proof of real model behavior.

This module owns the counterfactual -> verify lifecycle:

* **counterfactual()** - book one declared counterfactual pair for a
  system (minted ``cfn-N`` ids; pinned 8-term generation-method
  vocabulary and pinned plausibility verdicts ``plausible`` /
  ``implausible`` / ``inconclusive`` / ``unverifiable`` /
  ``not-assessed``). The first counterfactual registers its system.
  Raw inputs, outputs, perturbations, feature vectors, and attribution
  internals never enter records - digest pins only.
* **verify()** - pure read: re-derive the digest pin of any
  counterfactual record; verdict ``verified`` / ``tampered`` booked as
  data (tamper reported, never raised).
* **evaluate()** - pure read: per-system plausibility tallies and a
  ledger-rule posture derived as data; ``integrity_ok`` re-derives
  every in-scope digest pin as data.
* **retire()** - terminal retirement of a system id; ids are never
  recycled.

Distinct-layer rationale: ``counterfactual_explanation_probes.py``
owns the probe corpus plus deterministic quality gates and the
simulatability harness for explanation *surfaces* (attacker-facing
quality measurement); ``ai_explainability.py`` owns system-level
explanation *provisions* (``counterfactual`` is one of its pinned
explanation kinds, but only at the provision level) - this module is
the dedicated counterfactual *generation* ledger none of them own:
original decision -> declared minimal-change alternative -> declared
plausibility verdict, all booked as data.

House style: frozen dataclasses, caller-supplied strictly-increasing
int seqs (claim-then-burn: failed mutations consume their seq and book
an ``ai-counterfactual.rejected`` row; rewinds raise bare without
consuming), no wall-clock, RLock guarding, fail-closed taxonomy,
stdlib-only with the standard ``canonical_json`` try/except fallback,
``sha256:`` digest pins, and ``audit.ndjson/1`` events.

Honest scope: this module generates no counterfactuals, probes no
models, and proves nothing about real behavior. A booked ``plausible``
verdict means "the host declared it", never "the model would really
flip". Raw inputs, outputs, perturbations, features, attributions,
and model internals never enter records or cross the audit boundary -
digest pins only.
"""

